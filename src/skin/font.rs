/// Glyph rows as 5-bit masks (bit 4 = leftmost column).
fn table() -> &'static Vec<(char, [u8; 5])> {
    static T: OnceLock<Vec<(char, [u8; 5])>> = OnceLock::new();
    T.get_or_init(|| {
        GLYPHS
            .iter()
            .map(|(ch, rows)| {
                let mut m = [0u8; 5];
                for (i, r) in rows.iter().enumerate() {
                    for (j, b) in r.bytes().enumerate() {
                        if b == b'#' {
                            m[i] |= 1 << (4 - j);
                        }
                    }
                }
                (*ch, m)
            })
            .collect()
    })
}

fn glyph(ch: char) -> [u8; 5] {
    let ch = ch.to_ascii_uppercase();
    let t = table();
    t.iter()
        .find(|(c, _)| *c == ch)
        .or_else(|| t.iter().find(|(c, _)| *c == '?'))
        .map(|(_, m)| *m)
        .unwrap()
}

pub fn width(s: &str) -> i32 {
    s.chars().count() as i32 * CELL - 1
}

pub fn draw(px: &Px, x: i32, y: i32, s: &str, c: Color32) {
    for (i, ch) in s.chars().enumerate() {
        if ch == ' ' {
            continue;
        }
        let gx = x + i as i32 * CELL;
        for (ry, bits) in glyph(ch).iter().enumerate() {
            // Merge horizontal runs into single rects.
            let mut col = 0;
            while col < 5 {
                if bits & (1 << (4 - col)) != 0 {
                    let start = col;
                    while col < 5 && bits & (1 << (4 - col)) != 0 {
                        col += 1;
                    }
                    px.fill(gx + start, y + ry as i32, col - start, 1, c);
                } else {
                    col += 1;
                }
            }
        }
    }
}
